const q = (value: string | null | undefined) =>
  value === null || value === undefined ? "null" : `'${value.replace(/'/g, "''")}'`;
const qArray = (values: string[]) => `array[${values.map(q).join(", ")}]::text[]`;

/**
 * SQL that loads the units into Supabase. Safe to run again after editing:
 * rows are updated in place by stable id, so learners keep their progress.
 * Sentences removed from a file are left in the database (detached from
 * their lesson), never deleted, because learner reviews may point at them.
 */
export function unitsToSql(units: UnitFile[]): string {
  const out: string[] = [
    "-- Generated by `npm run content:build` from content/*.yaml. Do not edit by hand.",
    "-- Safe to run more than once.",
    "",
    "begin;",
    "",
  ];

  for (const unit of units) {
    const lang = unit.language;
    const unitRef = `(select u.id from public.units u join public.levels l on l.id = u.level_id
       where l.language_code = ${q(lang)} and l.number = ${unit.level} and u.slug = ${q(unit.unit)})`;
    const lessonRef = (slug: string) =>
      `(select le.id from public.lessons le where le.unit_id = ${unitRef} and le.slug = ${q(slug)})`;

    out.push(`-- ${lang} level ${unit.level}, unit ${unit.unit}`);
    out.push(
      `do $$ begin if ${unitRef} is null then raise exception 'unit ${unit.unit} (level ${unit.level}, ${lang}) is missing: run the migrations first'; end if; end $$;`,
    );

    unit.lessons.forEach((lesson, index) => {
      out.push(
        `insert into public.lessons (unit_id, position, slug, title) values (${unitRef}, ${index + 1}, ${q(lesson.slug)}, ${q(lesson.title)})
  on conflict (unit_id, slug) do update set position = excluded.position, title = excluded.title;`,
      );
    });

    const placed: { s: Sentence; lessonSlug: string | null; position: number | null }[] = [
      ...unit.lessons.flatMap((lesson) =>
        lesson.sentences.map((s, i) => ({ s, lessonSlug: lesson.slug, position: i + 1 })),
      ),
      ...unit.alternatives.map((s) => ({ s, lessonSlug: null, position: null })),
    ];

    for (const { s, lessonSlug, position } of placed) {
      out.push(
        `insert into public.sentences (id, language_code, lesson_id, position, text_roman, text_script, meaning_en, why_note,
    pronunciation_note, register, formality, region, validation_status, source_ref)
  values (${q(sentenceUuid(lang, s.id))}, ${q(lang)}, ${lessonSlug ? lessonRef(lessonSlug) : "null"}, ${position ?? "null"},
    ${q(s.roman)}, ${q(s.script)}, ${q(s.meaning)}, ${q(s.why)}, ${q(s.pronunciation)},
    ${q(s.register)}, ${q(s.formality)}, ${q(s.region)}, ${q(s.status)}, ${q(s.sources.join(" · ") || null)})
  on conflict (id) do update set lesson_id = excluded.lesson_id, position = excluded.position,
    text_roman = excluded.text_roman, text_script = excluded.text_script, meaning_en = excluded.meaning_en,
    why_note = excluded.why_note, pronunciation_note = excluded.pronunciation_note, register = excluded.register,
    formality = excluded.formality, region = excluded.region, validation_status = excluded.validation_status,
    source_ref = excluded.source_ref;`,
      );
    }

    const ids = placed.map(({ s }) => q(sentenceUuid(lang, s.id))).join(", ");
    out.push(`delete from public.sentence_tokens where sentence_id in (${ids});`);
    out.push(`delete from public.sentence_variants where sentence_id in (${ids});`);

    for (const { s } of placed) {
      s.tokens.forEach((t, i) => {
        out.push(
          `insert into public.sentence_tokens (sentence_id, position, surface_roman, lemma_roman, gloss_en, breakdown, grammar_tags)
  values (${q(sentenceUuid(lang, s.id))}, ${i + 1}, ${q(t.word)}, ${q(t.lemma)}, ${q(t.gloss)}, ${q(t.breakdown)}, ${qArray(t.tags)});`,
        );
      });
      for (const v of s.variants) {
        out.push(
          `insert into public.sentence_variants (sentence_id, variant_sentence_id, relation)
  values (${q(sentenceUuid(lang, s.id))}, ${q(sentenceUuid(lang, v.sentence))}, ${q(v.relation)});`,
        );
      }
    }
    out.push("");
  }

  out.push("commit;", "");
  return out.join("\n");
}
