import { createHash } from "node:crypto";
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { parse } from "yaml";
import { normaliseRoman, romanise } from "./romanise.ts";
import { type Sentence, type UnitFile, unitFileSchema } from "./schema.ts";

export type Problem = { file: string; where: string; message: string };

/** Stable UUID (version 5 layout) from a name, so re-loading keeps the same ids. */
export function stableUuid(name: string): string {
  const hash = createHash("sha1").update(`polyglot:${name}`).digest();
  hash[6] = (hash[6] & 0x0f) | 0x50;
  hash[8] = (hash[8] & 0x3f) | 0x80;
  const hex = hash.subarray(0, 16).toString("hex");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20, 32)}`;
}

export const sentenceUuid = (language: string, id: string) => stableUuid(`${language}:sentence:${id}`);

/** Everything wrong with one unit file. An empty list means it is ready to load. */
export function checkUnit(file: string, data: unknown): { unit?: UnitFile; problems: Problem[] } {
  const parsed = unitFileSchema.safeParse(data);
  if (!parsed.success) {
    return {
      problems: parsed.error.issues.map((issue) => ({
        file,
        where: issue.path.join("."),
        message: issue.message,
      })),
    };
  }

  const unit = parsed.data;
  const problems: Problem[] = [];
  const all: Sentence[] = [...unit.lessons.flatMap((l) => l.sentences), ...unit.alternatives];
  const ids = new Set<string>();

  for (const s of all) {
    const where = `sentence ${s.id}`;
    if (ids.has(s.id)) problems.push({ file, where, message: "id is used twice" });
    ids.add(s.id);

    // 1. The English-letter form must match the script, letter for letter.
    try {
      const fromScript = normaliseRoman(romanise(s.script));
      if (fromScript !== normaliseRoman(s.roman)) {
        problems.push({ file, where, message: `roman "${s.roman}" does not match script, which reads "${fromScript}"` });
      }
    } catch (error) {
      problems.push({ file, where, message: (error as Error).message });
    }

    // 2. The word-by-word breakdown must cover the sentence exactly.
    const joined = normaliseRoman(s.tokens.map((t) => t.word).join(" "));
    if (joined !== normaliseRoman(s.roman)) {
      problems.push({ file, where, message: `words "${joined}" do not add up to "${normaliseRoman(s.roman)}"` });
    }
  }

  for (const lesson of unit.lessons) {
    if (new Set(unit.lessons.map((l) => l.slug)).size !== unit.lessons.length) {
      problems.push({ file, where: `lesson ${lesson.slug}`, message: "lesson slug is used twice" });
      break;
    }
  }

  // 3. Variants must point at sentences that exist.
  for (const s of all) {
    for (const v of s.variants) {
      if (!ids.has(v.sentence)) {
        problems.push({ file, where: `sentence ${s.id}`, message: `variant "${v.sentence}" does not exist` });
      }
      if (v.sentence === s.id) {
        problems.push({ file, where: `sentence ${s.id}`, message: "a sentence cannot be its own variant" });
      }
    }
  }

  return { unit, problems };
}

export function loadContentDir(dir: string): { units: UnitFile[]; problems: Problem[] } {
  const units: UnitFile[] = [];
  const problems: Problem[] = [];
  // patterns.yaml is the sentence lab, checked separately (patterns.ts).
  for (const name of readdirSync(dir).filter((f) => f.endsWith(".yaml") && f !== "patterns.yaml").sort()) {
    const path = join(dir, name);
    let data: unknown;
    try {
      data = parse(readFileSync(path, "utf8"));
    } catch (error) {
      problems.push({ file: path, where: "file", message: (error as Error).message });
      continue;
    }
    const result = checkUnit(path, data);
    problems.push(...result.problems);
    if (result.unit) units.push(result.unit);
  }
  return { units, problems };
}

